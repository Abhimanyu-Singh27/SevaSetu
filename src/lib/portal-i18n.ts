type TranslationKey = keyof typeof translations.en;

export function normalizePortalLanguage(value: string | null | undefined): PortalLanguage {
  return value === "hi" ? "hi" : "en";
}

export function portalText(language: string | null | undefined, key: TranslationKey, values: Record<string, string | number> = {}) {
  const selected = translations[normalizePortalLanguage(language)][key] || translations.en[key];
  return selected.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

export function portalNavigation(language: string | null | undefined) {
  const translate = (key: TranslationKey) => portalText(language, key);
  return {
    dashboard: translate("dashboard"), searchServices: translate("searchServices"), requests: translate("requests"), serviceHistory: translate("serviceHistory"),
    messages: translate("messages"), savedWorkers: translate("savedWorkers"), reviews: translate("reviews"), notifications: translate("notifications"), profile: translate("profile"),
    activeServices: translate("activeServices"), completedServices: translate("completedServices"), myServices: translate("myServices"), skillsPricing: translate("skillsPricing"),
    availability: translate("availability"), analytics: translate("analytics"), verification: translate("verification"), settings: translate("settings"), language: translate("language"),
  };
}

